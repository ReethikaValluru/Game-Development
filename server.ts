import express, { Request, Response } from 'express';
import { createServer as createViteServer } from 'vite';
import { GoogleGenAI } from '@google/genai';
import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.dirname(fileURLToPath(import.meta.url));

dotenv.config();

const app = express();
const PORT = 3000;

app.use(express.json({ limit: '50mb' }));
app.use(express.urlencoded({ extended: true, limit: '50mb' }));

// Initialize GoogleGenAI client with server-side environment key
const getAiClient = () => {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    throw new Error('GEMINI_API_KEY environment variable is missing.');
  }
  return new GoogleGenAI({ apiKey });
};

// 1. High-Quality Image Generation (gemini-3-pro-image-preview)
// Supports user-specified image sizes: 1K, 2K, 4K
app.post('/api/generate-image', async (req: Request, res: Response) => {
  try {
    const { prompt, imageSize = '1K', aspectRatio = '16:9' } = req.body;

    if (!prompt || typeof prompt !== 'string') {
      return res.status(400).json({ error: 'Prompt is required.' });
    }

    const ai = getAiClient();

    // Call gemini-3-pro-image-preview via ai.interactions.create
    const interaction = await ai.interactions.create({
      model: 'gemini-3-pro-image-preview',
      input: `Historical archaeological visualization from Yuval Noah Harari's Sapiens: ${prompt}. Authentic prehistoric lighting, museum quality detail, no text, no modern logos.`,
      response_modalities: ['image'],
      generation_config: {
        image_config: {
          aspect_ratio: aspectRatio,
          image_size: ['1K', '2K', '4K'].includes(imageSize) ? imageSize : '1K',
        },
      },
    });

    let imageUrl: string | null = null;
    let mimeType = 'image/png';

    for (const step of interaction.steps || []) {
      if (step.type === 'model_output' && Array.isArray((step as any).content)) {
        const imageContent = (step as any).content.find((c: any) => c.type === 'image');
        if (imageContent && imageContent.data) {
          mimeType = imageContent.mime_type || 'image/png';
          imageUrl = `data:${mimeType};base64,${imageContent.data}`;
          break;
        }
      }
    }

    if (!imageUrl && interaction.output_image?.data) {
      mimeType = interaction.output_image.mime_type || 'image/png';
      imageUrl = `data:${mimeType};base64,${interaction.output_image.data}`;
    }

    if (!imageUrl) {
      return res.status(500).json({ error: 'No image was generated by the model.' });
    }

    return res.json({
      imageUrl,
      modelUsed: 'gemini-3-pro-image-preview',
      imageSize,
      aspectRatio,
    });
  } catch (error: unknown) {
    console.error('Image generation error:', error);
    const errMessage = error instanceof Error ? error.message : 'Unknown error during image generation';
    return res.status(500).json({ error: errMessage });
  }
});

// 2. Animate Images into Video (gemini-omni-1.2-flash via Interactions API)
// Mandatory aspect ratios: 16:9 or 9:16
app.post('/api/animate-video', async (req: Request, res: Response) => {
  try {
    const { imageBase64, mimeType = 'image/png', prompt, aspectRatio = '16:9' } = req.body;

    if (!imageBase64 || typeof imageBase64 !== 'string') {
      return res.status(400).json({ error: 'imageBase64 is required.' });
    }

    const ai = getAiClient();

    // Strip data URL header if present
    const cleanBase64 = imageBase64.replace(/^data:[a-zA-Z0-9/+-]+;base64,/, '');

    // Mandatory aspect ratio check: 16:9 or 9:16
    const selectedRatio: '16:9' | '9:16' = aspectRatio === '9:16' ? '9:16' : '16:9';

    const motionPrompt = prompt ||
      'Animate this historical prehistoric scene with natural atmospheric wind, swaying grasslands, living tribal campfire glow, and gentle camera drift.';

    const interaction = await ai.interactions.create(
      {
        model: 'gemini-omni-1.2-flash',
        input: [
          {
            type: 'image',
            mime_type: mimeType,
            data: cleanBase64,
          },
          {
            type: 'text',
            text: motionPrompt,
          },
        ],
        background: false,
        store: false,
        stream: false,
        response_format: {
          type: 'video',
          aspect_ratio: selectedRatio,
          duration: '5s',
          resolution: '720p',
        },
      },
      { timeout: 300000 }
    );

    const videoPart = interaction.output_video;
    if (videoPart && videoPart.data) {
      const videoDataUrl = `data:${videoPart.mime_type || 'video/mp4'};base64,${videoPart.data}`;
      return res.json({
        videoUrl: videoDataUrl,
        aspectRatio: selectedRatio,
        model: 'gemini-omni-1.2-flash',
      });
    }

    if (videoPart && videoPart.uri) {
      return res.json({
        videoUrl: videoPart.uri,
        aspectRatio: selectedRatio,
        model: 'gemini-omni-1.2-flash',
      });
    }

    return res.status(500).json({ error: 'Video generation completed but output video was empty.' });
  } catch (error: unknown) {
    console.error('Video animation error:', error);
    const errMessage = error instanceof Error ? error.message : 'Unknown error during video generation';
    return res.status(500).json({ error: errMessage });
  }
});

// 3. Harari Chronicler Consultation (gemini-3.8-flash)
app.post('/api/chronicler', async (req: Request, res: Response) => {
  try {
    const { userQuestion, era = 'cognitive', gameStateSnapshot } = req.body;

    const ai = getAiClient();
    const systemPrompt = `You are the Chronicler of Humankind, inspired directly by Yuval Noah Harari's bestselling book "Sapiens: A Brief History of Humankind".
You provide profound, engaging, and historically grounded answers about:
- The Cognitive Revolution: Why fictitious language and shared myths (gods, nations, money) enable cooperation in bands exceeding Dunbar's number (150).
- The Agricultural Revolution: Why Harari calls wheat domestication "history's biggest fraud" and the "luxury trap".
- The Unification of Humankind: How money, empires, and universal religions bound disparate bands together.
- The Scientific Revolution: How admitting ignorance ("Ignoramus") sparked empirical progress and technological mastery.
Keep your answer concise (2-3 paragraphs), thought-provoking, and reference concepts from Sapiens.`;

    const interaction = await ai.interactions.create({
      model: 'gemini-3.8-flash',
      input: `Player is in Era: ${era}. Game situation: ${JSON.stringify(gameStateSnapshot || {})}.
Question: "${userQuestion}"`,
      system_instruction: systemPrompt,
    });

    const reply = interaction.output_text || 'The chronicles of human imagination remain vast and mysterious.';
    return res.json({ reply });
  } catch (error: unknown) {
    console.error('Chronicler error:', error);
    const errMessage = error instanceof Error ? error.message : 'Chronicler failed to consult history.';
    return res.status(500).json({ error: errMessage });
  }
});

// Setup Vite middleware in dev or static files in production
async function startServer() {
  if (process.env.NODE_ENV !== 'production') {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(projectRoot, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(projectRoot, 'dist', 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Server listening on http://0.0.0.0:${PORT}`);
  });
}

startServer();
